    /// A component's header: `\0asm` + version 13, layer 1.
    const COMPONENT_HEADER: [u8; 8] = [0x00, 0x61, 0x73, 0x6d, 0x0d, 0x00, 0x01, 0x00];

    #[test]
    fn a_core_module_is_diagnosed_as_such() {
        let diag = diagnose_not_a_component(&CORE_MODULE_HEADER).expect("must diagnose");
        assert!(diag.contains("core module"), "{diag}");
        // The message has to name the RIGHT tool: since the SDK (ADR-0024) a
        // step is built with the plain toolchain, and sending someone to
        // install `cargo component` would send whoever is already lost down
        // the wrong road.
        assert!(
            diag.contains("cargo build --target wasm32-wasip2"),
            "{diag}"
        );
    }

    #[test]
    fn a_component_does_not_trigger_the_diagnosis() {
        assert_eq!(diagnose_not_a_component(&COMPONENT_HEADER), None);
    }

    /// Issue #24: a component whose `run` takes `attempt: u32` instead of the
    /// WIT's `s32` — the exact mistake BUG-06 made during the beta — used to
    /// fail with wasmtime's bare "failed to convert function to given type"
    /// and nothing else. `tests/fixtures/firma_no_casa.wasm` is a real
    /// component built against a hand-edited copy of `wit/anvil-step.wit`
