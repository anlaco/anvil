/// The contract version this bridge speaks (ADR-0020 §4).
///
/// **It is copied by hand, and that is exactly what the ADR warns is
/// dangerous.** It cannot be imported from `modelo` because this crate
/// deliberately does not link it: `modelo` uses prost 0.14 and the `pb` here is
/// generated by tonic 0.12 with prost 0.13 (see `Cargo.toml`).
///
/// What keeps them from drifting apart is the test
/// `the_bridge_contract_is_the_one_in_modelo`, which does link `modelo` (as a
/// dev-dependency, without touching the binary) and compares the two numbers.
/// If someone raises the contract in `modelo` and forgets this one, that test
/// goes red — which is the difference between a compile error and **an echo
/// that lies**.
const CONTRACT: i32 = 4;

// Bindings for the `anvil:step` WIT (this crate's `wit/` is the source of
// truth for the contract; the component's author uses the same file).
bindgen!({
    path: "wit",
    world: "anvil-step",
});

/// The component's state: WASI context (empty — the component is a pure
/// function, with no files and no network) plus wasmtime's resource table.
struct State {
    wasi: WasiCtx,
    table: ResourceTable,
}

impl WasiView for State {
    fn ctx(&mut self) -> WasiCtxView<'_> {
        WasiCtxView {
            ctx: &mut self.wasi,
            table: &mut self.table,
        }
    }
}

/// The instantiated component, ready for `run` to be called. It is loaded
/// **once** at start-up (preload, like TestStand) and reused for every call:
/// 1 Store, N calls.
struct LoadedComponent {
    store: Store<State>,
    step: AnvilStep,
}

/// Tells apart, by looking at the 8 header bytes, the two failures wasmtime
/// reports with the **same** text ("failed to parse WebAssembly module"): a
/// file that is not WASM at all, and a *core* module compiled as such instead
/// of as a component. The second is stumble #1 for whoever writes their first
/// step, and wasmtime's message makes them blame the toolchain (DIAG-5).
///
/// The header is `\0asm` + version: core modules carry `01 00 00 00` and
/// components `0d 00 01 00` (layer 1). Looking at the bytes, rather than at the
/// error text, keeps the diagnosis safe from wasmtime rewording it.
fn diagnose_not_a_component(bytes: &[u8]) -> Option<String> {
    if bytes.len() < 8 || &bytes[0..4] != b"\0asm" {
        return Some(
            "not a WebAssembly file: it does not start with the '\\0asm' header".to_string(),
        );
    }
    if bytes[4..8] == [0x01, 0x00, 0x00, 0x00] {
        return Some(
            "this is a WebAssembly core module, not a component: build it with \
             'cargo build --target wasm32-wasip2' and check that the crate calls \
             'anvil_step::export!()' (see docs/guia-inicio-rapido.md)"
                .to_string(),
        );
    }
    None
}

/// The `anvil:step/step` interface's export key, as wit-bindgen/wasm-tools
/// name it: `<package>/<interface>@<version>` (see `wit/anvil-step.wit`).
const STEP_INTERFACE: &str = "anvil:step/step@0.4.0";

/// The signatures `wit/anvil-step.wit` declares, spelled by hand for
/// [`diagnose_signature_mismatch`] — this binary does not parse WIT text at
/// runtime, so these are not read from the file. Keep them in step with the
/// `run`/`describe` lines there.
const EXPECTED_RUN: &str =
    "run: func(name: string, attempt: s32, inputs: list<named>) -> step-result";
const EXPECTED_DESCRIBE: &str = "describe: func() -> list<step-spec>";

/// A component-model type, spelled close to its WIT syntax — deep enough to
/// name a mismatched parameter's actual type (issue #24's `u32` instead of
/// `s32`, or a `record` wrapping the arguments). Not a full WIT printer: past
/// one level of nesting a composite type just names its shape.
fn render_type(t: &CompType) -> String {
    match t {
        CompType::Bool => "bool".to_string(),
        CompType::S8 => "s8".to_string(),
        CompType::U8 => "u8".to_string(),
        CompType::S16 => "s16".to_string(),
        CompType::U16 => "u16".to_string(),
        CompType::S32 => "s32".to_string(),
        CompType::U32 => "u32".to_string(),
        CompType::S64 => "s64".to_string(),
        CompType::U64 => "u64".to_string(),
        CompType::Float32 => "float32".to_string(),
        CompType::Float64 => "float64".to_string(),
        CompType::Char => "char".to_string(),
        CompType::String => "string".to_string(),
        CompType::List(l) => format!("list<{}>", render_type(&l.ty())),
        CompType::Option(o) => format!("option<{}>", render_type(&o.ty())),
        CompType::Record(r) => {
            let fields = r
                .fields()
                .map(|f| format!("{}: {}", f.name, render_type(&f.ty)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("record {{ {fields} }}")
        }
        CompType::Map(_) => "map".to_string(),
        CompType::Tuple(_) => "tuple".to_string(),
        CompType::Variant(_) => "variant".to_string(),
        CompType::Enum(_) => "enum".to_string(),
        CompType::Result(_) => "result".to_string(),
        CompType::Flags(_) => "flags".to_string(),
        CompType::Own(_) | CompType::Borrow(_) => "resource".to_string(),
        CompType::Future(_) => "future".to_string(),
        CompType::Stream(_) => "stream".to_string(),
        CompType::ErrorContext => "error-context".to_string(),
    }
}

/// Renders a component-model function type as a WIT-like `name: func(...) ->
/// ...` line, the same shape as [`EXPECTED_RUN`]/[`EXPECTED_DESCRIBE`] so the
/// two read side by side.
fn render_func(name: &str, f: &types::ComponentFunc) -> String {
    let params = f
        .params()
        .map(|(n, t)| format!("{n}: {}", render_type(&t)))
        .collect::<Vec<_>>()
        .join(", ");
    let results: Vec<String> = f.results().map(|t| render_type(&t)).collect();
    let ret = match results.len() {
        0 => String::new(),
        1 => format!(" -> {}", results[0]),
        _ => format!(" -> ({})", results.join(", ")),
    };
    format!("{name}: func({params}){ret}")
}

/// Finds a function exported by a component instance, by name.
fn find_func(
    instance: &types::ComponentInstance,
    engine: &Engine,
    name: &str,
) -> Option<types::ComponentFunc> {
    instance.exports(engine).find_map(|(n, e)| match e.ty {
        types::ComponentItem::ComponentFunc(f) if n == name => Some(f),
        _ => None,
    })
}

/// Issue #24: wasmtime's own error on a signature mismatch — "failed to
/// convert function to given type" — names neither the signature the host
/// expected nor the one the component exports, so the first thing whoever
/// writes their own component sees is a message with no pointer to what is
/// wrong (BUG-06 of the beta). This inspects the component's *type* — no WASM
/// runs, it is the same static info `wasm-tools component wit` would read —
/// to say both, so the two can be compared by eye.
///
/// Always run/described side by side, even when one of the two turns out to
/// match: a `render_func` line expands named types structurally (`list<named>`
/// comes back as `list<record { name: string, value: variant }>`), so it
/// never reads identical to [`EXPECTED_RUN`]/[`EXPECTED_DESCRIBE`]'s shorthand
/// even for a correct component. Deciding "this one actually differs" would
/// need a real WIT-aware comparison; showing both lines and letting the
/// reader's eye do that is the honest alternative to a hand-rolled one that
/// could itself be wrong.
fn diagnose_signature_mismatch(component: &Component, engine: &Engine) -> String {
    let ty = component.component_type();
    let interface = ty.exports(engine).find_map(|(name, e)| match e.ty {
        types::ComponentItem::ComponentInstance(i) if name == STEP_INTERFACE => Some(i),
        _ => None,
    });
    let Some(interface) = interface else {
        let found: Vec<&str> = ty.exports(engine).map(|(n, _)| n).collect();
        return format!(
            "the component does not export '{STEP_INTERFACE}'; it exports: {}",
            if found.is_empty() {
                "(nothing)".to_string()
            } else {
                found.join(", ")
            }
        );
    };
    [("run", EXPECTED_RUN), ("describe", EXPECTED_DESCRIBE)]
        .iter()
        .map(|(name, expected)| {
            let found = find_func(&interface, engine, name)
                .map(|f| render_func(name, &f))
                .unwrap_or_else(|| format!("{name}: (not exported)"));
            format!("expected  {expected}\nexports   {found}")
        })
        .collect::<Vec<_>>()
        .join("\n")
}

impl LoadedComponent {
    fn load(engine: &Engine, bytes: &[u8]) -> Result<Self, String> {
        // Before instantiating anything: if the `.wasm` is not a component,
        // say so with the real reason instead of wasmtime's generic one.
        if let Some(diag) = diagnose_not_a_component(bytes) {
            return Err(diag);
        }
        let mut linker = Linker::new(engine);
        wasmtime_wasi::p2::add_to_linker_sync(&mut linker)
            .map_err(|e| format!("WASI linker: {e}"))?;
        // No preopens and no network: a real sandbox. The component only does
        // its job; it does not touch the host.
        let state = State {
            wasi: WasiCtx::builder().build(),
            table: ResourceTable::new(),
        };
        let mut store = Store::new(engine, state);
        let component =
            Component::from_binary(engine, bytes).map_err(|e| format!("invalid component: {e}"))?;
        let step = AnvilStep::instantiate(&mut store, &component, &linker).map_err(|e| {
            format!(
                "could not instantiate: {e}\n{}",
                diagnose_signature_mismatch(&component, engine)
            )
        })?;
        Ok(LoadedComponent { store, step })
    }

    /// Calls the component's `run` and translates the result into the
    /// contract's protobuf. A guest failure (panic, trap) is reported as
    /// `Status::internal`: the engine sees it as a step error, and does not cut
    /// the sequence over the network.
    // `clippy::result_large_err`: the `Err` is `tonic::Status` (176 bytes),
    // tonic's canonical error type. Boxing it just for this method would force
    // unwrapping it at every point where tonic expects it, in exchange for
    // nothing: this is called once per step, not in a hot loop.
    #[allow(clippy::result_large_err)]
    fn call(&mut self, name: &str, attempt: i32, inputs: &[Named]) -> Result<StepResult, Status> {
        let r = self
            .step
            .anvil_step_step()
            .call_run(&mut self.store, name, attempt, inputs)
            .map_err(|e| Status::internal(format!("step '{name}' failed: {e}")))?;
        Ok(StepResult {
            name: name.to_string(),
            status: r.status,
            message: r.message,
            measured_value: r.measured_value.map(|v| v.to_string()).unwrap_or_default(),
            limit_min: String::new(),
            limit_max: String::new(),
            outputs: r.outputs.iter().map(named_to_proto).collect(),
            // **The bridge answers the echo on the component's behalf**
            // (ADR-0020 §4d). A component knows nothing of gRPC, protobuf or
            // contract versions (ADR-0015); the bridge is the only translator,
            // and therefore the only one that knows which contract number goes
            // with which WIT version. If it got this far, the `.wasm` matched
            // `anvil:step@0.4.0` —wasmtime fails to instantiate otherwise— so
            // it speaks this binary's contract.
            contract: CONTRACT,
        })
    }

    /// Asks the component for its catalog and translates it into the
    /// contract's protobuf.
    ///
    /// Called once, at start-up (ADR-0021 §3), and its cost is that of one WASM
    /// call: the component returns a list built at compile time by the SDK.
    #[allow(clippy::result_large_err)]
    fn describe(&mut self) -> Result<Vec<pb::StepSpec>, Status> {
        let specs = self
            .step
            .anvil_step_step()
            .call_describe(&mut self.store)
            .map_err(|e| {
                Status::internal(format!("the component could not describe itself: {e}"))
            })?;
        Ok(specs.iter().map(spec_to_proto).collect())
    }
}

/// The separator between a module's logical name and a step's, in the name
/// that travels in `StepRequest.name` (ADR-0025 §2).
///
/// The qualified name rides **inside the existing field**, which is an opaque
/// string as far as `paso.proto` is concerned. That is what lets a department
/// serve many modules without touching the contract, the engine or the WIT.
const MODULE_SEP: char = '/';

/// One module the bridge serves: a `.wasm` under its working directory.
///
/// The **logical name is the file stem** (`multimetro.wasm` → `multimetro`),
/// so neither the extension nor the path ever reaches the sequence
/// (ADR-0025 §3): rewriting a module in another language, or the department
/// reorganising its folders, must not edit anybody's YAML.
struct Module {
    path: PathBuf,
    /// SHA-256 of the artifact, computed when the set is built — that is, by
    /// reading the file, without compiling anything. Asking a department for
    /// its hashes has to stay cheap, because it is what invalidates an
    /// editor's catalog cache (ADR-0025 §5).
    hash: String,
    /// `None` until something actually needs this module. Loading is what
    /// costs (wasmtime compiles the component), so it is paid per module and
    /// on demand: `--validate` with no catalog compiles nothing, and a broken
    /// `.wasm` sitting in the folder no longer takes the whole bridge down —
    /// only whoever uses it fails.
    loaded: Option<LoadedComponent>,
}

/// What this bridge serves: one or more modules, and how a step name maps onto
/// them.
struct ModuleSet {
    engine: Engine,
    modules: BTreeMap<String, Module>,
    /// Whether step names carry a `module/` prefix.
    ///
    /// It comes from what the bridge was pointed at, and the two modes are
    /// kept apart on purpose rather than blended: `--wasm <file>` serves one
    /// module and steps keep their **bare** names, which is what every
    /// sequence written before ADR-0025 says; `--modules <dir>` serves the
    /// whole folder and steps are **qualified**. Mixing them would make
    /// `medir_voltaje` mean different things depending on what else happens to
    /// be in the directory.
    qualified: bool,
}

impl ModuleSet {
    /// The single-file mode: one module, bare step names. What `--wasm` gives.
    ///
    /// This one is loaded **eagerly**, unlike the directory mode. Laziness is
    /// there so that one broken `.wasm` in a folder does not take down the
    /// modules nobody asked about; with a single file pointed at by hand there
    /// are no others, and finding out at the first step that it is not a
    /// component —or is a core module, DIAG-5— would be finding out with the
    /// unit already on the bench.
    fn from_file(engine: Engine, path: &Path) -> Result<Self, String> {
        let mut modules = BTreeMap::new();
        let (name, mut module) = read_module(path)?;
        let bytes =
            std::fs::read(path).map_err(|e| format!("could not read '{}': {e}", path.display()))?;
        module.loaded = Some(
            LoadedComponent::load(&engine, &bytes)
                .map_err(|e| format!("could not load the component '{}': {e}", path.display()))?,
        );
        modules.insert(name, module);
        Ok(ModuleSet {
            engine,
            modules,
            qualified: false,
        })
    }

    /// The directory mode: every `*.wasm` in the given directories, qualified
    /// step names. What `--modules` gives.
    fn from_dirs(engine: Engine, dirs: &[PathBuf]) -> Result<Self, String> {
        let mut modules: BTreeMap<String, Module> = BTreeMap::new();
        for dir in dirs {
            let entries = std::fs::read_dir(dir).map_err(|e| {
                format!(
                    "could not read the module directory '{}': {e}",
                    dir.display()
                )
            })?;
            for entry in entries {
                let path = entry
                    .map_err(|e| format!("could not read an entry of '{}': {e}", dir.display()))?
                    .path();
                if path.extension().and_then(|e| e.to_str()) != Some("wasm") {
                    continue;
                }
                let (name, module) = read_module(&path)?;
                // Two files with the same logical name would make a step name
                // ambiguous, and serving the wrong one is worse than not
                // starting: it would run a different step than the one the
                // sequence asked for, and the report would not say so.
                if let Some(previous) = modules.get(&name) {
                    return Err(format!(
                        "two modules are both called '{name}': '{}' and '{}'. A module's logical \
                         name is its file stem, so rename one of the two files",
                        previous.path.display(),
                        path.display()
                    ));
                }
                modules.insert(name, module);
            }
        }
        if modules.is_empty() {
            let list = dirs
                .iter()
                .map(|d| d.display().to_string())
                .collect::<Vec<_>>()
                .join(", ");
            return Err(format!(
                "no '.wasm' module found under: {list}. An executor finds its modules \
                 next to its own binary (ADR-0027), so copy them there — or point it \
                 elsewhere with --modules <dir>"
            ));
        }
        Ok(ModuleSet {
            engine,
            modules,
            qualified: true,
        })
    }

    /// Splits a step name into (module, step).
    ///
    /// In single-file mode the whole name is the step's, and the module is the
    /// only one there is. In directory mode the prefix is required: guessing a
    /// module because there happens to be one that serves that step would make
    /// the sequence's meaning depend on the folder's contents.
    fn resolve(&self, name: &str) -> Result<(String, String), String> {
        if !self.qualified {
            let module = self
                .modules
                .keys()
                .next()
                .expect("single-file mode always has exactly one module");
            return Ok((module.clone(), name.to_string()));
        }
        let (module, step) = name.split_once(MODULE_SEP).ok_or_else(|| {
            format!(
                "step '{name}' has no module: this executor serves several modules, so a step is \
                 named '<module>{MODULE_SEP}<step>'. It serves: {}",
                self.module_names()
            )
        })?;
        if !self.modules.contains_key(module) {
            return Err(format!(
                "this executor serves no module called '{module}'. It serves: {}",
                self.module_names()
            ));
        }
        Ok((module.to_string(), step.to_string()))
    }

    fn module_names(&self) -> String {
        self.modules.keys().cloned().collect::<Vec<_>>().join(", ")
    }

    /// The module's component, loading it the first time it is needed.
    fn component(&mut self, module: &str) -> Result<&mut LoadedComponent, String> {
        // Split borrow: `engine` and `modules` are different fields, and
        // taking them apart is what lets the load happen behind `&mut self`.
        let ModuleSet {
            engine, modules, ..
        } = self;
        let m = modules
            .get_mut(module)
            .ok_or_else(|| format!("unknown module '{module}'"))?;
        if m.loaded.is_none() {
            let bytes = std::fs::read(&m.path)
                .map_err(|e| format!("could not read '{}': {e}", m.path.display()))?;
            let loaded = LoadedComponent::load(engine, &bytes).map_err(|e| {
                format!(
                    "could not load the module '{module}' ({}): {e}",
                    m.path.display()
                )
            })?;
            m.loaded = Some(loaded);
        }
        Ok(m.loaded.as_mut().expect("just loaded"))
    }

    /// The catalog of every module, with each step's name qualified.
    ///
    /// A module that cannot be loaded, or that traps while describing itself,
    /// **does not take the other modules' catalog down with it**: its steps
    /// stay out and the reason goes to stderr. Anvil then reports those steps
    /// as unchecked, which is ADR-0021 §4 — not being checked is not the same
    /// as being fine, and it is said out loud.
    // `clippy::result_large_err`: the inner `Result` is `describe`'s, whose
    // `Err` is `tonic::Status` — see the note on `LoadedComponent::call`.
    #[allow(clippy::result_large_err)]
    fn catalog(&mut self) -> Vec<pb::StepSpec> {
        let names: Vec<String> = self.modules.keys().cloned().collect();
        let qualified = self.qualified;
        let mut out = Vec::new();
        for module in names {
            let specs = match self.component(&module).map(|c| c.describe()) {
                Ok(Ok(specs)) => specs,
                Ok(Err(status)) => {
                    eprintln!(
                        "anvil-exec-wasm: module '{module}' could not describe itself ({}); its \
                         steps stay unchecked",
                        status.message()
                    );
                    continue;
                }
                Err(e) => {
                    eprintln!(
                        "anvil-exec-wasm: module '{module}' could not be loaded ({e}); its steps \
                         stay unchecked"
                    );
                    continue;
                }
            };
            out.extend(specs.into_iter().map(|mut s| {
                if qualified {
                    s.name = format!("{module}{MODULE_SEP}{}", s.name);
                }
                s
            }));
        }
        out
    }
}

/// Reads a `.wasm` off disk: its logical name and its hash, without compiling
/// it. Loading is deferred to `ModuleSet::component`.
fn read_module(path: &Path) -> Result<(String, Module), String> {
    let name = path
        .file_stem()
        .and_then(|s| s.to_str())
        .ok_or_else(|| format!("'{}' has no usable file name", path.display()))?
        .to_string();
    let bytes =
        std::fs::read(path).map_err(|e| format!("could not read '{}': {e}", path.display()))?;
    let hash = format!("{:x}", Sha256::digest(&bytes));
    Ok((
        name,
        Module {
            path: path.to_path_buf(),
            hash,
            loaded: None,
        },
    ))
}

/// The `StepExecutor` gRPC service (the engine's contract). Every `Invoke`
/// resolves its module and delegates to the component.
///
/// The `Mutex` is the standard (blocking) one: wasmtime's `run` call is
/// synchronous and the engine is sequential (one request at a time per
/// client), so there is no contention. If parallelism ever arrives,
/// `spawn_blocking` is what keeps the async runtime from stalling.
struct ExecutorService {
    modules: Arc<Mutex<ModuleSet>>,
}

#[tonic::async_trait]
impl StepExecutor for ExecutorService {
    // `clippy::result_large_err`: the `Err` is `tonic::Status`, tonic's
    // canonical error type — see the note on `LoadedComponent::call`.
    #[allow(clippy::result_large_err)]
    async fn invoke(&self, request: Request<StepRequest>) -> Result<Response<StepResult>, Status> {
        let req = request.into_inner();
        // A parameter whose `oneof` arrived with no branch does not say what
        // type it is. It cannot be passed to the component, and it cannot be
        // silently dropped: dropping it would mean the step measured without it
        // and nobody found out (ADR-0019, Rule 2).
        let inputs = req
            .inputs
            .iter()
            .map(proto_to_named)
            .collect::<Result<Vec<_>, _>>()
            .map_err(|e| match e {
                NotTranslatable::Untyped(n) => Status::invalid_argument(format!(
                    "parameter '{n}' arrived with no type (none of the number/text/boolean branches)"
                )),
                NotTranslatable::Reference(n) => Status::invalid_argument(format!(
                    "parameter '{n}' is an object reference, and a WASM component cannot hold \
                     one: the 'anvil:step' interface is a function with no state between calls, \
                     so it has nowhere to keep the object. Serve that step from a 'grpc' \
                     executor of its own process (ADR-0022 §8)"
                )),
            })?;
        // `block_in_place`: the wasmtime call is **blocking**, and the
        // synchronous WASI bindings do a `block_on` over the tokio runtime from
        // the inside to service the component's stdout/stderr. Called directly
        // from this async method, a step's first `println!` —or the message a
        // `panic!` prints— dies with "Cannot start a runtime from within a
        // runtime", takes the bridge's worker down with it and cuts the
        // sequence with the unit on the bench. Moving the call off the thread
        // that drives the runtime is what keeps a debug print a debug print
        // (RF-12).
        let response = tokio::task::block_in_place(|| {
            let mut set = self
                .modules
                .lock()
                .map_err(|_| Status::internal("executor in use"))?;
            // Which module, and what the step is called inside it. A name that
            // does not resolve is `invalid_argument` and names what is served:
            // the sequence asked for something this department does not have,
            // and that is information about the bench, never about the unit
            // (ADR-0019, Rule 2).
            let (module, step) = set.resolve(&req.name).map_err(Status::invalid_argument)?;
            let mut result = set.component(&module).map_err(Status::internal)?.call(
                &step,
                req.attempt,
                &inputs,
            )?;
            // The engine routed on the qualified name and expects it back:
            // `StepResult.name` is what the report is written from.
            result.name = req.name.clone();
            Ok::<_, Status>(result)
        })?;
        Ok(Response::new(response))
    }

    /// The component's catalog, asked through the WIT's second door
    /// (`anvil:step@0.4.0`) and translated (ADR-0021 §1, ADR-0024).
    ///
    /// Until 0.4.0 this answered `describes = false` and there was nothing else
    /// it could do: the interface exported a single `run(name, attempt,
    /// inputs)`, the component dispatched by name inside itself, and from out
    /// here there was no list of names to publish and no signature to read. The
    /// WIT embedded in the `.wasm` did not help either — it said *"there is a
    /// `run` that takes a name and a list"*, which is true and useless. That
    /// was the bill for dispatching by name (ADR-0003); `describe` is the bill
    /// being paid.
    ///
    /// **An empty list is read as `describes = false`.** In gRPC the boolean
    /// tells apart "I serve nothing" from "do not check me" because an
    /// executor can legitimately serve zero steps; a component that serves
    /// zero steps has nothing to do, so the safe reading is the only useful
    /// one (ADR-0021 §4).
    ///
    /// A component that traps while describing itself is **not** a run-stopping
    /// error here: it comes back as `describes = false`, its steps come out as
    /// unchecked, and the sequence goes on — the same treatment as an executor
    /// that does not answer at all (`crates/motor/src/catalogo.rs`).
    #[allow(clippy::result_large_err)]
    async fn describe(&self, _r: Request<CatalogRequest>) -> Result<Response<Catalog>, Status> {
        // `block_in_place` for the same reason as in `invoke`, above.
        let steps = tokio::task::block_in_place(|| {
            Ok::<_, Status>(
                self.modules
                    .lock()
                    .map_err(|_| Status::internal("executor in use"))?
                    .catalog(),
            )
        })?;
        Ok(Response::new(Catalog {
            describes: !steps.is_empty(),
            steps,
            contract: CONTRACT,
            // Empty on purpose: with no objects there is no life to declare
            // (ADR-0022 §6). A component cannot hold one — the bridge rejects
            // a reference before it gets here.
            lifetime: String::new(),
        }))
    }
}

/// The directory this binary lives in — where its modules are, unless it was
/// told otherwise (ADR-0027).
///
/// Resolved from the executable itself and not from the working directory: the
/// bridge is spawned by `anvil`, which has its own cwd, and a department has to
/// mean the same thing wherever it is launched from.
fn own_directory() -> Result<PathBuf, String> {
    let exe = std::env::current_exe()
        .map_err(|e| format!("could not locate this executor's own binary: {e}"))?;
    exe.parent()
        .map(|d| d.to_path_buf())
        .ok_or_else(|| "this executor's binary has no directory".to_string())
}

/// What the bridge was told to serve.
struct Args {
    wasm: Option<PathBuf>,
    modules: Vec<PathBuf>,
    port: u16,
    bind: IpAddr,
    /// `--list`: print the catalog and exit, without listening. The
    /// *enumerate* operation of ADR-0025 §4 — what an editor needs, and what
    /// answers "which steps does this executor serve?" without starting a
    /// bench. The same door the Python executor already has.
    list: bool,
}

fn parse_args() -> Result<Args, String> {
    let mut wasm: Option<PathBuf> = None;
    let mut modules: Vec<PathBuf> = Vec::new();
    let mut port: u16 = 0;
    let mut bind: IpAddr = "127.0.0.1".parse().unwrap();
    let mut list = false;
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--wasm" => {
                i += 1;
                wasm = Some(PathBuf::from(args.get(i).ok_or("--wasm with no value")?));
            }
            "--modules" => {
                i += 1;
                modules.push(PathBuf::from(args.get(i).ok_or("--modules with no value")?));
            }
            "--list" => list = true,
            "--port" => {
                i += 1;
                port = args
                    .get(i)
                    .ok_or("--port with no value")?
                    .parse()
                    .map_err(|_| "--port is not a number")?;
            }
            "--bind" => {
                i += 1;
                bind = args
                    .get(i)
                    .ok_or("--bind with no value")?
                    .parse()
                    .map_err(|_| "--bind is not a valid IP")?;
            }
            other => return Err(format!("unknown flag: '{other}'")),
        }
        i += 1;
    }
    if wasm.is_some() && !modules.is_empty() {
        return Err(
            "--wasm and --modules are exclusive: one file, or one or more directories".to_string(),
        );
    }
    // Nothing said: **the executor finds its own modules**, next to its own
    // binary (ADR-0027). That is what makes a department a copyable folder —
    // the bridge and its `.wasm` together — and what keeps the path to them
    // out of anybody's sequence. Anvil is told where the executor is; where
    // its modules are is the executor's business.
    if wasm.is_none() && modules.is_empty() {
        modules.push(own_directory()?);
    }
    Ok(Args {
        wasm,
        modules,
        port,
        bind,
        list,
    })
}

/// `--list`: every module, its hash and the steps it serves with their
/// signature. Loads each module, because describing is the only way to know —
/// which is why this is a tooling operation and not something a run does
/// (ADR-0025 §4).
// `clippy::result_large_err`: as in `ModuleSet::catalog`, above.
#[allow(clippy::result_large_err)]
fn print_catalog(set: &mut ModuleSet) {
    let names: Vec<String> = set.modules.keys().cloned().collect();
    for module in names {
        let hash = set.modules[&module].hash.clone();
        let path = set.modules[&module].path.display().to_string();
        println!("{module}  sha256:{hash}");
        println!("    {path}");
        let specs = match set.component(&module).map(|c| c.describe()) {
            Ok(Ok(specs)) => specs,
            Ok(Err(status)) => {
                println!("    (does not describe itself: {})", status.message());
                continue;
            }
            Err(e) => {
                println!("    (could not be loaded: {e})");
                continue;
            }
        };
        if specs.is_empty() {
            println!("    (serves no steps)");
            continue;
        }
        for s in specs {
            let signature = s
                .inputs
                .iter()
                .map(|p| {
                    let t = match pb::ValueType::try_from(p.r#type) {
                        Ok(pb::ValueType::Number) => "number",
                        Ok(pb::ValueType::Text) => "text",
                        Ok(pb::ValueType::Boolean) => "boolean",
                        Ok(pb::ValueType::Reference) => "reference",
                        _ => "unspecified",
                    };
                    if p.required {
                        format!("{}: {t}", p.name)
                    } else {
                        format!("{}: {t} = optional", p.name)
                    }
                })
                .collect::<Vec<_>>()
                .join(", ");
            // Printed exactly as a sequence must write it: qualified only when
            // this executor serves several modules. A listing that showed a
            // prefix the YAML must not carry would be a listing that lies.
            if set.qualified {
                println!("    {module}{MODULE_SEP}{}({signature})", s.name);
            } else {
                println!("    {}({signature})", s.name);
            }
            if !s.doc.is_empty() {
                println!("        {}", s.doc);
            }
            if !s.outputs.is_empty() {
                let outs = s
                    .outputs
                    .iter()
                    .map(|o| o.name.clone())
                    .collect::<Vec<_>>()
                    .join(", ");
                println!("        outputs: {outs}");
            }
        }
    }
}

fn main() {
    let args = match parse_args() {
        Ok(x) => x,
        Err(e) => {
            eprintln!(
                "usage: anvil-exec-wasm (--wasm <path.wasm> | --modules <dir>...) \
                 [--port <port>] [--bind <ip>] [--list]\n{e}"
            );
            std::process::exit(2);
        }
    };

    let engine = Engine::default();

    // The modules are read (name and hash) but **not compiled** here: loading
    // is per module and on demand, so a folder holding one broken `.wasm` still
    // serves the rest, and `--validate` with no catalog compiles nothing.
    let set = match &args.wasm {
        Some(path) => ModuleSet::from_file(engine, path),
        None => ModuleSet::from_dirs(engine, &args.modules),
    };
    let mut set = match set {
        Ok(s) => s,
        Err(e) => {
            eprintln!("anvil-exec-wasm: {e}");
            std::process::exit(1);
        }
    };

    if args.list {
        print_catalog(&mut set);
        return;
    }

    // The hash goes into the log on every start: with the module named
    // logically, this is what says which artifact actually answered
    // (ADR-0025 §6). It is **not** yet in the run's report — that needs a field
    // in the contract, and its own ADR.
    for (name, m) in &set.modules {
        eprintln!(
            "anvil-exec-wasm: module '{name}' ({}) sha256:{}",
            m.path.display(),
            m.hash
        );
    }

    let addr = SocketAddr::new(args.bind, args.port);
    let service = ExecutorService {
        modules: Arc::new(Mutex::new(set)),
    };

    let rt = match tokio::runtime::Runtime::new() {
        Ok(rt) => rt,
        Err(e) => {
            eprintln!("could not create the runtime: {e}");
            std::process::exit(1);
        }
    };

    let server = Server::builder()
        .add_service(StepExecutorServer::new(service))
        .serve(addr);

    eprintln!("anvil-exec-wasm: listening on {addr}");

    // Clean exit: the host spawns the bridge with stdin piped; when the host
    // dies (or drops the `Child`), the pipe closes → EOF → the bridge exits.
    // Without this, a dead host would leave the bridge orphaned.
    let current_stdin = std::io::stdin();
    let _ = thread::spawn(move || {
        let mut buf = [0u8; 1];
        while let Ok(n) = std::io::Read::read(&mut current_stdin.lock(), &mut buf) {
            if n == 0 {
                std::process::exit(0);
            }
        }
    });

    // The server does not finish on its own (a loop serving requests). The
    // host kills the process when the sequence ends; by hand, Ctrl-C.
    let _ = rt.block_on(server);
}

#[cfg(test)]
